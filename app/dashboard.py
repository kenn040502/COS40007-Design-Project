@app.route("/api/ts/live")
def api_ts_live():
    """SSE endpoint — runs ARIMA live on national CPI inflation and streams progress."""
    try:
        horizon = min(max(int(request.args.get("horizon", 24)), 1), 48)
    except ValueError:
        horizon = 24

    def generate():
        from src.time_series import run_live
        inflation_path = os.path.join(PROCESSED_DIR, "overall_inflation.csv")
        if not os.path.exists(inflation_path):
            yield f'data: {json.dumps({"type": "error", "message": "Run the pipeline first."})}\n\n'
            return
        inflation_df = _load_df("overall_inflation.csv")
        inflation_df = inflation_df.copy()
        inflation_df["date"] = pd.to_datetime(inflation_df["date"])
        for event in run_live(inflation_df, horizon=horizon):
            yield f"data: {json.dumps(event)}\n\n"

    return Response(
        stream_with_context(generate()),
        mimetype="text/event-stream",
        headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"},
    )


